import type { Context } from "probot";
import { chat, truncate } from "./llm.js";

const SYSTEM_PROMPT = `You are an experienced maintainer triaging GitHub issues.
Given an issue title and body, respond with:
1. A short classification: Bug / Feature request / Question / Other.
2. 2-4 possible causes or approaches, as a markdown bullet list.
3. Suggested next steps or clarifying questions to ask the reporter.
Be concise (max ~250 words). Use GitHub-flavored markdown. If the issue is unclear, say what information is missing.`;

const MAX_BODY_TOKENS = 3000;

export async function triageIssue(
  context: Context<"issues.opened">,
): Promise<void> {
  const { issue, repository } = context.payload;

  // Skip PRs (issues webhook fires for PRs too) and bots.
  if (issue.pull_request || issue.user?.type === "Bot") return;

  context.log.info(`Triaging issue #${issue.number} in ${repository.full_name}`);

  const suggestion = await chat([
    { role: "system", content: SYSTEM_PROMPT },
    {
      role: "user",
      content: `Issue #${issue.number}: ${issue.title}\n\n${truncate(issue.body ?? "(no body)", MAX_BODY_TOKENS)}`,
    },
  ]);

  await context.octokit.rest.issues.createComment({
    owner: repository.owner.login,
    repo: repository.name,
    issue_number: issue.number,
    body: `🤖 **AI Triage**\n\n${suggestion}\n\n<sub>Generated by the Probot AI assistant — human review still required.</sub>`,
  });

  context.log.info(`Posted AI triage on issue #${issue.number}`);
}
